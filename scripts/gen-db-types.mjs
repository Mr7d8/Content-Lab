// Generates packages/core/src/db.ts (Supabase-style Database types) from a
// Postgres database that has the migrations applied.
//
//   DATABASE_URL=postgres://... pnpm db:types
//
// With the Supabase CLI linked to the project, `supabase gen types typescript`
// produces the same shape and can be used instead.
import { writeFile } from 'node:fs/promises';
import pg from 'pg';

const url = process.env.DATABASE_URL;
if (!url) {
  console.error('Set DATABASE_URL to a database with the migrations applied.');
  process.exit(1);
}

const client = new pg.Client({ connectionString: url });
await client.connect();

const { rows: columns } = await client.query(`
  select c.table_name, c.column_name, c.data_type, c.udt_name, c.is_nullable,
         c.column_default, c.is_identity, c.identity_generation, c.is_generated
  from information_schema.columns c
  join information_schema.tables t
    on t.table_schema = c.table_schema and t.table_name = c.table_name
  where c.table_schema = 'public' and t.table_type = 'BASE TABLE'
  order by c.table_name, c.ordinal_position`);

const { rows: fks } = await client.query(`
  select con.conname as name, src.relname as table_name, dst.relname as referenced,
         array(select a.attname::text from unnest(con.conkey) with ordinality k(n, i)
               join pg_attribute a on a.attrelid = con.conrelid and a.attnum = k.n order by k.i) as columns,
         array(select a.attname::text from unnest(con.confkey) with ordinality k(n, i)
               join pg_attribute a on a.attrelid = con.confrelid and a.attnum = k.n order by k.i) as referenced_columns
  from pg_constraint con
  join pg_class src on src.oid = con.conrelid
  join pg_class dst on dst.oid = con.confrelid
  join pg_namespace ns on ns.oid = src.relnamespace
  join pg_namespace nd on nd.oid = dst.relnamespace
  where con.contype = 'f' and ns.nspname = 'public' and nd.nspname = 'public'
  order by src.relname, con.conname`);

const { rows: uniques } = await client.query(`
  select src.relname as table_name,
         array(select a.attname::text from unnest(con.conkey) k(n)
               join pg_attribute a on a.attrelid = con.conrelid and a.attnum = k.n) as columns
  from pg_constraint con
  join pg_class src on src.oid = con.conrelid
  join pg_namespace ns on ns.oid = src.relnamespace
  where con.contype in ('p', 'u') and ns.nspname = 'public'`);

const { rows: functions } = await client.query(`
  select p.proname as name, pg_get_function_result(p.oid) as result
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.pronargs = 0
    and pg_get_function_result(p.oid) <> 'trigger'
  order by p.proname`);

await client.end();

const scalar = {
  uuid: 'string', text: 'string', varchar: 'string', timestamptz: 'string', timestamp: 'string',
  date: 'string', int2: 'number', int4: 'number', int8: 'number', numeric: 'number',
  float4: 'number', float8: 'number', bool: 'boolean', jsonb: 'Json', json: 'Json',
};
function tsType(col) {
  if (col.data_type === 'ARRAY') {
    const inner = scalar[col.udt_name.replace(/^_/, '')];
    if (!inner) throw new Error(`Unmapped array type ${col.udt_name} on ${col.table_name}.${col.column_name}`);
    return `${inner}[]`;
  }
  const t = scalar[col.udt_name];
  if (!t) throw new Error(`Unmapped type ${col.udt_name} on ${col.table_name}.${col.column_name}`);
  return t;
}

const tables = new Map();
for (const col of columns) {
  if (!tables.has(col.table_name)) tables.set(col.table_name, []);
  tables.get(col.table_name).push(col);
}

const indent = (n) => ' '.repeat(n);
let out = `// Generated by scripts/gen-db-types.mjs from supabase/migrations. Do not edit by hand.

export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];

export type Database = {
  public: {
    Tables: {
`;
for (const [table, cols] of tables) {
  const row = [], insert = [], update = [];
  for (const col of cols) {
    const base = tsType(col);
    const nullable = col.is_nullable === 'YES';
    const type = nullable ? `${base} | null` : base;
    row.push(`${col.column_name}: ${type}`);
    if (col.is_identity === 'YES' && col.identity_generation === 'ALWAYS' || col.is_generated === 'ALWAYS') {
      insert.push(`${col.column_name}?: never`);
      update.push(`${col.column_name}?: never`);
      continue;
    }
    const optional = nullable || col.column_default !== null || col.is_identity === 'YES';
    insert.push(`${col.column_name}${optional ? '?' : ''}: ${type}`);
    update.push(`${col.column_name}?: ${type}`);
  }
  const rels = fks.filter((fk) => fk.table_name === table).map((fk) => {
    const oneToOne = uniques.some((u) => u.table_name === table && u.columns.length === fk.columns.length
      && fk.columns.every((c) => u.columns.includes(c)));
    return `{
${indent(12)}foreignKeyName: '${fk.name}';
${indent(12)}columns: [${fk.columns.map((c) => `'${c}'`).join(', ')}];
${indent(12)}isOneToOne: ${oneToOne};
${indent(12)}referencedRelation: '${fk.referenced}';
${indent(12)}referencedColumns: [${fk.referenced_columns.map((c) => `'${c}'`).join(', ')}];
${indent(10)}}`;
  });
  const block = (name, fields) => `${indent(8)}${name}: {\n${fields.map((f) => `${indent(10)}${f};`).join('\n')}\n${indent(8)}};\n`;
  out += `${indent(6)}${table}: {\n`;
  out += block('Row', row) + block('Insert', insert) + block('Update', update);
  out += `${indent(8)}Relationships: [${rels.length ? `\n${indent(10)}${rels.join(`,\n${indent(10)}`)},\n${indent(8)}` : ''}];\n`;
  out += `${indent(6)}};\n`;
}
const fnResult = { boolean: 'boolean', numeric: 'number', integer: 'number', bigint: 'number', text: 'string' };
const fnType = (result) => fnResult[result] ?? 'unknown';
out += `    };
    Views: { [_ in never]: never };
    Functions: {
${functions.map((f) => `      ${f.name}: { Args: Record<PropertyKey, never>; Returns: ${fnType(f.result)} };`).join('\n')}
    };
    Enums: { [_ in never]: never };
    CompositeTypes: { [_ in never]: never };
  };
};

type PublicTables = Database['public']['Tables'];
export type Tables<T extends keyof PublicTables> = PublicTables[T]['Row'];
export type TablesInsert<T extends keyof PublicTables> = PublicTables[T]['Insert'];
export type TablesUpdate<T extends keyof PublicTables> = PublicTables[T]['Update'];
`;

const target = new URL('../packages/core/src/db.ts', import.meta.url);
await writeFile(target, out);
console.log(`Wrote ${tables.size} tables to packages/core/src/db.ts`);
